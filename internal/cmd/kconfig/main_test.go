func TestUpdateBuildfileErrorsOnDuplicateRule(t *testing.T) {
	input := []byte(`kconfig_import(name = "sample")
kconfig_import(name = "sample")
`)
	_, err := updateBuildfile(input, "BUILD.bazel", "sample", map[string]string{})
	if err == nil {
		t.Fatal("updateBuildfile() succeeded on duplicate rule")
	}
}

func TestFormatConfigFlagsIsDeterministic(t *testing.T) {
	got := build.FormatString(configFlagsExpr(map[string]string{
		"CONFIG_A": "y",
		"CONFIG_Z": "m",
	}))
	want := `{
    "CONFIG_A": "y",
    "CONFIG_Z": "m",
}`
	if got != want {
		t.Fatalf("configFlagsExpr() =\n%s\nwant:\n%s", got, want)
	}
}

func TestConfigBuildfile(t *testing.T) {
	got, err := configBuildfile("BUILD.bazel", "kconfig", "//pkg:source.config", map[string]string{
		"CONFIG_A":   "y",
		"CONFIG_MOD": "m",
	}, []string{"//pkg:__pkg__"})
	if err != nil {
		t.Fatalf("configBuildfile() failed: %v", err)
	}

	want := `# Generated by kconfig. Do not edit.

load("@linux.bzl//internal:kconfig.bzl", "kconfig_file")

exports_files(["BUILD.bazel"])

kconfig_file(
    name = "kconfig",
    config = "//pkg:source.config",
    config_flags = {
        "CONFIG_A": "y",
        "CONFIG_MOD": "m",
    },
    visibility = ["//pkg:__pkg__"],
)
`
	if string(got) != want {
		t.Fatalf("configBuildfile() =\n%s\nwant:\n%s", got, want)
	}
}
