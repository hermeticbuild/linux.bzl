package main

import (
	"reflect"
	"strings"
	"testing"

	build "github.com/bazelbuild/buildtools/build"
)

func TestParseKconfig(t *testing.T) {
	got, err := parseKconfig(strings.NewReader(`
CONFIG_BOOL=y
CONFIG_MODULE=m
# CONFIG_DISABLED is not set
CONFIG_FALSE=n
CONFIG_STRING="value"
CONFIG_INT=12
CONFIG_HEX=0x1f
CONFIG_lower-case.symbol=m

# unrelated comment
`))
	if err != nil {
		t.Fatalf("parseKconfig() failed: %v", err)
	}

	want := map[string]string{
		"CONFIG_BOOL":              "y",
		"CONFIG_FALSE":             "n",
		"CONFIG_HEX":               "0x1f",
		"CONFIG_INT":               "12",
		"CONFIG_MODULE":            "m",
		"CONFIG_STRING":            `"value"`,
		"CONFIG_lower-case.symbol": "m",
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("parseKconfig() = %#v, want %#v", got, want)
	}
}

func TestParseKconfigRejectsDuplicates(t *testing.T) {
	_, err := parseKconfig(strings.NewReader("CONFIG_DUP=y\nCONFIG_DUP=m\n"))
	if err == nil {
		t.Fatal("parseKconfig() succeeded on duplicate key")
	}
}

func TestUpdateBuildfileRewritesNamedRule(t *testing.T) {
	input := []byte(`load("@linux.bzl//internal:kconfig.bzl", "kconfig_import")

kconfig_import(
    name = "other",
    config_flags = {
        "CONFIG_KEEP": "y",
    },
)

kconfig_import(
    name = "sample",
    config_flags = {
        "CONFIG_OLD": "y",
    },
)
`)
	got, err := updateBuildfile(input, "BUILD.bazel", "sample", map[string]string{
		"CONFIG_ALPHA": "y",
		"CONFIG_MOD":   "m",
	})
	if err != nil {
		t.Fatalf("updateBuildfile() failed: %v", err)
	}

	want := `load("@linux.bzl//internal:kconfig.bzl", "kconfig_import")

kconfig_import(
    name = "other",
    config_flags = {
        "CONFIG_KEEP": "y",
    },
)

kconfig_import(
    name = "sample",
    config_flags = {
        "CONFIG_ALPHA": "y",
        "CONFIG_MOD": "m",
    },
)
`
	if string(got) != want {
		t.Fatalf("updateBuildfile() =\n%s\nwant:\n%s", got, want)
	}
}

